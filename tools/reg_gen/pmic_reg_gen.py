"""
Generates a PMIC Register Bank (pmic_regbank.sv + pmic_regbank_pkg.sv) and
its real_bits[][] verification matrix from SystemRDL using PeakRDL.

Uses a custom PeakRDL CpuifBase subclass (SimpleRegbankCpuif) so PeakRDL natively
generates:
  - 5 simple register ports: reg_addr_i, reg_wdata_i, reg_we_i, reg_re_i, reg_rdata_o
  - A holding flip-flop output stage on reg_rdata_o (updated on reg_re_i)
  - Packed structs hwif_in (RO status inputs) and hwif_out (RW trimming outputs)
"""

import argparse
from pathlib import Path
from systemrdl import RDLCompiler
from systemrdl.node import RegNode
from peakrdl_regblock import RegblockExporter
from peakrdl_regblock.cpuif.base import CpuifBase
from peakrdl_regblock.udps import ALL_UDPS
from rdl_post_process import postprocess_sv


class SimpleRegbankCpuif(CpuifBase):
    template_path = "simple_regbank_tmpl.sv"

    @property
    def port_declaration(self) -> str:
        # Expose full 8-bit (or wider) address port even if address map has fewer registers
        port_addr_width = max(8, self.addr_width)
        lines = [
            f"input wire [{port_addr_width-1}:0] reg_addr_i",
            f"input wire [{self.data_width-1}:0] reg_wdata_i",
            "input wire reg_we_i",
            "input wire reg_re_i",
            f"output logic [{self.data_width-1}:0] reg_rdata_o",
        ]
        return ",\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="PMIC SystemRDL Register Bank Generator")
    parser.add_argument(
        "--input-file",
        default="src/rdl/pmic_registers.rdl",
        help="Input SystemRDL file",
    )
    parser.add_argument(
        "--output-dir",
        default="src/csr",
        help="Output directory for generated SV files",
    )
    parser.add_argument(
        "--py-mask-file",
        default="verification/cocotb/top/i3c_simple_target/pmic_real_bits.py",
        help="Output Python file for real_bits[][] verification masks",
    )
    args = parser.parse_args()

    rdlc = RDLCompiler()
    for udp in ALL_UDPS:
        rdlc.register_udp(udp)
    rdlc.compile_file(args.input_file)
    root = rdlc.elaborate()

    exporter = RegblockExporter()
    exporter.export(
        root,
        args.output_dir,
        cpuif_cls=SimpleRegbankCpuif,
        retime_read_response=False,  # Holding FF is generated directly by SimpleRegbankCpuif
    )

    out_dir = Path(args.output_dir)
    postprocess_sv(str(out_dir / "pmic_regbank.sv"))
    postprocess_sv(str(out_dir / "pmic_regbank_pkg.sv"))

    # Extract real_bits[][] (writable RW bits and read-only RO status bits) from RDL AST
    rw_masks = {}
    ro_masks = {}
    reg_names = {}

    for node in root.descendants():
        if isinstance(node, RegNode):
            addr = node.address_offset
            reg_names[addr] = node.inst_name
            rw_bits = [0] * 8
            ro_bits = [0] * 8
            for field in node.fields():
                for b in range(field.low, field.high + 1):
                    if field.is_sw_writable:
                        rw_bits[b] = 1
                    elif field.is_sw_readable:
                        ro_bits[b] = 1
            rw_masks[addr] = rw_bits
            ro_masks[addr] = ro_bits

    max_addr = max(rw_masks.keys()) if rw_masks else 0
    num_regs = max_addr + 1

    py_out = Path(args.py_mask_file)
    py_out.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Auto-generated by tools/reg_gen/pmic_reg_gen.py from SystemRDL",
        "",
        f"NUM_PMIC_REGS = {num_regs}",
        "",
        "# real_bits[addr][bit]: 1 if bit is a writable RW flip-flop, 0 if empty or RO",
        "REAL_BITS = [",
    ]
    for addr in range(num_regs):
        bits = rw_masks.get(addr, [0] * 8)
        name = reg_names.get(addr, "UNMAPPED")
        mask_hex = sum(bits[b] << b for b in range(8))
        lines.append(f"    {bits},  # 0x{addr:02X} {name} (rw_mask=0x{mask_hex:02X})")
    lines.append("]")
    lines.append("")
    lines.append("# status_bits[addr][bit]: 1 if bit is a read-only hardware status input")
    lines.append("STATUS_BITS = [")
    for addr in range(num_regs):
        bits = ro_masks.get(addr, [0] * 8)
        name = reg_names.get(addr, "UNMAPPED")
        mask_hex = sum(bits[b] << b for b in range(8))
        lines.append(f"    {bits},  # 0x{addr:02X} {name} (ro_mask=0x{mask_hex:02X})")
    lines.append("]")
    lines.append("")

    py_out.write_text("\n".join(lines))
    print(f"Successfully generated {args.output_dir}/pmic_regbank.sv, pmic_regbank_pkg.sv, and {py_out}")


if __name__ == "__main__":
    main()
